const fs = require('fs');
const path = require('path');

const mapsDir = path.join(__dirname, 'standalone', 'data', 'maps');
const mapFiles = fs.readdirSync(mapsDir).filter(f => f.endsWith('.json'));
const maps = {};
for (const f of mapFiles) {
  const id = f.replace('.json', '');
  maps[id] = JSON.parse(fs.readFileSync(path.join(mapsDir, f), 'utf8'));
}

const embPath = path.join(__dirname, 'standalone', 'data', 'embedded.js');
const orig = fs.readFileSync(embPath, 'utf8');
const tileManifestMatch = orig.match(/tileManifest:\s*(\{.*\}),\s*schedule:/);
const scheduleMatch = orig.match(/schedule:\s*(\{.*?\})\s*\};/);

if (!tileManifestMatch || !scheduleMatch) {
  console.error('Failed to match tileManifest or schedule');
  process.exit(1);
}

const out = '// Generated by make-embedded: inline copies of the map JSONs, tile manifest and\n' +
  '// schedule so the game works when opened directly from disk (file://), where fetch() is blocked.\n' +
  '(function () {\n  "use strict";\n' +
  '  window.CC_EMBED = {\n' +
  '    maps: ' + JSON.stringify(maps) + ',\n' +
  '    tileManifest: ' + tileManifestMatch[1] + ',\n' +
  '    schedule: ' + scheduleMatch[1] + '\n' +
  '  };\n' +
  '})();\n';

fs.writeFileSync(embPath, out, 'utf8');
console.log('Successfully updated embedded.js with', Object.keys(maps).length, 'maps:');
console.log(Object.keys(maps));

